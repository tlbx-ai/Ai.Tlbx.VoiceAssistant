import assert from 'node:assert/strict';
import { OpenAiDirectRealtimeClient } from '../../Provider/Ai.Tlbx.VoiceAssistant.Provider.OpenAi.AspNetCore/wwwroot/voice-assistant-direct-realtime.js';
globalThis.window = globalThis;
const sent = [], text = [], chat = [];
const client = new OpenAiDirectRealtimeClient({ onTextDelta: t => text.push(t), onChatMessage: m => chat.push(m) });
client.sendRealtimeEvent = e => sent.push(e);
client.sendControl = () => {};
client.clientResponseControl = true;
client.interruptResponse = false;
client.textOnly = true;
const event = (type, rest = {}) => client.handleRealtimeEvent({ type, ...rest });
event('input_audio_buffer.committed');
event('input_audio_buffer.committed');
assert.equal(sent.length, 1, 'reserve response before server acknowledges');
event('response.created', { response: { id: 'r1' } });
event('input_audio_buffer.speech_started');
assert.equal(sent.length, 1, 'speech must not cancel');
let finishTool;
let calls = 0;
client.requestServerTool = async () => { calls++; return new Promise(resolve => { finishTool = resolve; }); };
const toolEvent = { call_id: 'c1', name: 'get_weather', arguments: '{"Location":"Nordhausen"}' };
const execution = client.executeServerTool(toolEvent);
await client.executeServerTool(toolEvent);
event('response.done', { response: { id: 'r1', status: 'completed', output: [] } });
event('input_audio_buffer.committed');
assert.equal(sent.length, 1, 'wait for in-flight tool even after more speech');
finishTool('Demo-Wetter: 17 Grad');
await execution;
assert.equal(calls, 1);
assert.deepEqual(sent.map(e => e.type), ['response.create', 'conversation.item.create', 'response.create']);
event('response.created', { response: { id: 'r2' } });
event('response.output_text.delta', { delta: 'Demo-Wetter: ' });
event('input_audio_buffer.speech_started');
event('response.output_text.delta', { delta: '17 Grad' });
event('response.output_text.done', { text: 'Demo-Wetter: 17 Grad' });
event('response.done', { response: { id: 'r2', status: 'completed', output: [] } });
assert.equal(text.join(''), 'Demo-Wetter: 17 Grad');
assert.equal(chat.filter(m => m.content === 'Demo-Wetter: 17 Grad' && m.role === 'assistant').length, 1);
assert.equal(sent.length, 3, 'no response loop');
// A tool that finishes after stop must never leak into the next session.
const late = client.executeServerTool({ ...toolEvent, call_id: 'c2' });
await client.stop();
finishTool('obsolete');
await late;
assert.equal(sent.length, 3);
// The existing conversational default still interrupts.
client.interruptResponse = true;
client.activeResponse = true;
event('input_audio_buffer.speech_started');
assert.equal(sent.at(-1).type, 'response.cancel');
console.log('WebRTC conversation support: streaming, speech/tool overlap, deduplication, stop isolation and voice default passed.');

// Normal voice mode keeps server-driven VAD and its existing tool continuation.
const voiceSent = [], statuses = [];
const voice = new OpenAiDirectRealtimeClient({ onStatus: s => statuses.push(s) });
voice.sendRealtimeEvent = e => voiceSent.push(e);
voice.sendControl = () => {};
voice.requestServerTool = async () => '17 Grad';
voice.handleRealtimeEvent({ type: 'input_audio_buffer.committed' });
assert.equal(voiceSent.length, 0, 'default VAD remains server-controlled');
voice.handleRealtimeEvent({ type: 'input_audio_buffer.speech_stopped' });
assert.equal(statuses.at(-1), 'Processing', 'normal voice status retained');
voice.handleRealtimeEvent({ type: 'response.created', response: { id: 'voice1' } });
await voice.executeServerTool(toolEvent);
assert.deepEqual(voiceSent.map(e => e.type), ['conversation.item.create', 'response.create']);
voice.handleRealtimeEvent({ type: 'response.output_audio.delta', delta: 'AAAA' });
assert.equal(statuses.at(-1), 'Speaking');
await voice.stop();

// Opt-in voice client control must not create a new response before cancellation completes.
const controlled = new OpenAiDirectRealtimeClient({});
const controlledSent = [];
controlled.clientResponseControl = true;
controlled.sendRealtimeEvent = e => controlledSent.push(e);
controlled.sendControl = () => {};
const send = (type, rest = {}) => controlled.handleRealtimeEvent({ type, ...rest });
send('input_audio_buffer.committed');
send('input_audio_buffer.speech_started');
send('input_audio_buffer.speech_started');
send('input_audio_buffer.speech_stopped');
send('input_audio_buffer.committed');
send('error', { error: { code: 'response_cancel_not_active' } });
assert.deepEqual(controlledSent.map(e => e.type), ['response.create', 'response.cancel']);
send('response.created', { response: { id: 'reserved' } });
send('response.done', { response: { id: 'reserved', status: 'cancelled', output: [] } });
assert.equal(controlledSent.at(-1).type, 'response.create');
assert.equal(controlledSent.length, 3, 'one follow-up after cancellation completion');
send('response.done', { response: { id: 'next', status: 'completed', output: [] } });

// A tool finishing during speech waits for the new committed turn in client-controlled voice mode.
let releaseVoiceTool;
controlled.requestServerTool = () => new Promise(resolve => { releaseVoiceTool = resolve; });
const voiceTool = controlled.executeServerTool(toolEvent);
send('input_audio_buffer.speech_started');
releaseVoiceTool('weather');
await voiceTool;
assert.equal(controlledSent.at(-1).type, 'conversation.item.create');
send('input_audio_buffer.speech_stopped');
send('input_audio_buffer.committed');
assert.equal(controlledSent.at(-1).type, 'response.create');
await controlled.stop();
console.log('Voice-to-voice regression contracts: default audio/tool behavior, status, cancel reservation and tool/speech overlap passed.');
